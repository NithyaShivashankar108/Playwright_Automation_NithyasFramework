const StatusCode = ""
if (StatusCode ===  "Bus"){
    console.log ("6 Wheels")
}
else if (StatusCode === "Car"){
    console.log ("4 Wheels")
}
else if (StatusCode === "Lorry"){
    console.log ("10 Wheels")
}
else if (StatusCode === "None"){
    console.log (" Road is Empty")
}
else {
    console.log ("Invalid Status Code")
}